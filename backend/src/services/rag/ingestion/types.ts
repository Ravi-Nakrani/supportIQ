import { z } from 'zod';

/**
 * Frontmatter schema required for all ShopEase Markdown policy documents.
 */
export const FrontmatterSchema = z.object({
  id: z
    .string()
    .trim()
    .min(1, "Frontmatter 'id' is required")
    .regex(/^[a-z0-9-]+$/, "Frontmatter 'id' must be kebab-case (e.g., 'shopease-returns-policy')"),
  title: z
    .string()
    .trim()
    .min(1, "Frontmatter 'title' is required"),
  category: z
    .string()
    .trim()
    .min(1, "Frontmatter 'category' is required"),
  version: z
    .string()
    .trim()
    .regex(/^\d+\.\d+\.\d+$/, "Frontmatter 'version' must follow semver format (e.g. '1.0.0')"),
  effectiveDate: z
    .string()
    .trim()
    .regex(/^\d{4}-\d{2}-\d{2}$/, "Frontmatter 'effectiveDate' must be in 'YYYY-MM-DD' format"),
});

export type DocumentFrontmatter = z.infer<typeof FrontmatterSchema>;

/**
 * Source document representation loaded from disk.
 */
export interface SourceDocument {
  frontmatter: DocumentFrontmatter;
  rawContent: string;
  sourcePath: string;
}

/**
 * Metadata retained on every individual text chunk.
 */
export interface ChunkMetadata {
  sourceId: string;
  sourceTitle: string;
  category: string;
  documentVersion: string;
  effectiveDate: string;
  sectionTitle: string;
  headingHierarchy: string[];
  sourcePath: string;
  chunkIndex: number;      // 0-based, document-wide sequential index
  contentHash: string;     // SHA-256 of normalized text
  metadataHash: string;    // SHA-256 of canonical metadata
}

/**
 * Canonical chunk object produced by the ingestion pipeline.
 */
export interface KnowledgeChunk {
  id: string;              // Deterministic: `${sourceId}#${slug(sectionTitle)}#${chunkIndex}`
  text: string;
  metadata: ChunkMetadata;
}

/**
 * Document-level summary recorded inside the manifest.
 */
export interface DocumentManifestSummary {
  sourceId: string;
  sourceTitle: string;
  category: string;
  version: string;
  effectiveDate: string;
  sourcePath: string;
  sectionCount: number;
  totalChunks: number;
}

/**
 * Canonical manifest file structure persisted to disk.
 */
export interface ManifestData {
  manifestVersion: string;
  generatedAt: string;
  documentCount: number;
  chunkCount: number;
  documents: DocumentManifestSummary[];
  chunks: KnowledgeChunk[];
}

/**
 * Four-category change report generated by comparing chunks against existing manifest.
 */
export interface IngestionChangeReport {
  added: KnowledgeChunk[];
  updated: KnowledgeChunk[];       // Chunks with changed content or metadata-only changes
  unchanged: KnowledgeChunk[];
  removed: Array<{ id: string; sourceId: string; sectionTitle: string }>;
  isIdempotent: boolean;           // True when added=0, updated=0, removed=0
}

/**
 * Overall ingestion execution result.
 */
export interface IngestionResult {
  manifest: ManifestData;
  report: IngestionChangeReport;
  summary: {
    totalDocuments: number;
    totalChunks: number;
    addedCount: number;
    updatedCount: number;
    unchangedCount: number;
    removedCount: number;
    isIdempotent: boolean;
  };
}

