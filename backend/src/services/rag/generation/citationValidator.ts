import { RetrievedChunk } from '../retrieval/types.js';
import { RawLlmCitation, SourceCitation } from './types.js';

/**
 * Normalizes whitespace in strings (collapses consecutive whitespace characters into a single space).
 */
export function normalizeWhitespace(text: string): string {
  return text.replace(/\s+/g, ' ').trim();
}

/**
 * Basic XML entity unescaping helper for quote matching.
 */
function unescapeXml(text: string): string {
  return text
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'");
}

export interface DroppedCitation {
  chunkId: string;
  quote: string;
  reason: string;
}

export interface CitationValidationResult {
  /**
   * Verified citations passing both chunk ID existence and quote substring verification.
   */
  validatedCitations: SourceCitation[];
  /**
   * Rejected citations with explicit diagnostic reasons.
   */
  droppedCitations: DroppedCitation[];
  /**
   * True if the answer claimed to have sufficient evidence, but zero valid citations survived validation.
   */
  isUngrounded: boolean;
}

export interface ValidateCitationsOptions {
  /**
   * Maximum allowed citations (bounded to retrieved chunk count).
   */
  maxCitations?: number;
}

/**
 * Strict programmatic citation validator verifying source integrity.
 *
 * Checks:
 * 1. Tier 1: Citation ID Validation - chunkId must exist in the retrieved chunk result set.
 * 2. Tier 2: Source Integrity Check - quote must be a verifiable substring of the chunk text after whitespace normalization.
 *
 * Any citation failing either check is discarded. NO synthetic replacement excerpt is generated.
 */
export class CitationValidator {
  /**
   * Validates candidate citations against the retrieved chunk set.
   *
   * @param candidateCitations Array of citations generated by the LLM.
   * @param retrievedChunks Actual chunks retrieved from vector search.
   * @param hasSufficientEvidence Whether the LLM claimed to have sufficient policy evidence.
   * @param options Optional configuration bounding total citation count.
   * @returns Detailed validation result including surviving citations and ungrounded flag.
   */
  validate(
    candidateCitations: RawLlmCitation[],
    retrievedChunks: RetrievedChunk[],
    hasSufficientEvidence: boolean,
    options?: ValidateCitationsOptions
  ): CitationValidationResult {
    const chunkMap = new Map<string, RetrievedChunk>();
    for (const chunk of retrievedChunks) {
      chunkMap.set(chunk.id, chunk);
    }

    const maxAllowed = options?.maxCitations ?? retrievedChunks.length;
    const validatedCitations: SourceCitation[] = [];
    const droppedCitations: DroppedCitation[] = [];
    const seenChunkIds = new Set<string>();

    for (const candidate of candidateCitations) {
      const chunkId = candidate.chunkId?.trim();
      const quote = candidate.quote?.trim();

      // 1. Validate chunkId is non-empty
      if (!chunkId) {
        droppedCitations.push({
          chunkId: '',
          quote: quote ?? '',
          reason: 'Citation chunkId is empty or undefined.',
        });
        continue;
      }

      // 2. Tier 1: Citation ID Validation - check ID exists in retrieved set
      const matchingChunk = chunkMap.get(chunkId);
      if (!matchingChunk) {
        droppedCitations.push({
          chunkId,
          quote: quote ?? '',
          reason: `Chunk ID "${chunkId}" was not present in the retrieved chunk set.`,
        });
        continue;
      }

      // 3. Deduplicate multiple citations pointing to the exact same chunk
      if (seenChunkIds.has(chunkId)) {
        droppedCitations.push({
          chunkId,
          quote: quote ?? '',
          reason: `Duplicate citation for chunk "${chunkId}".`,
        });
        continue;
      }

      // 4. Validate quote is non-empty
      if (!quote || quote.length === 0) {
        droppedCitations.push({
          chunkId,
          quote: '',
          reason: 'Citation quote is empty.',
        });
        continue;
      }

      // 5. Tier 2: Source Integrity Check - verify quote exists in chunk text
      const normalizedChunkText = normalizeWhitespace(matchingChunk.text).toLowerCase();
      const normalizedQuote = normalizeWhitespace(quote).toLowerCase();
      const unescapedNormalizedQuote = normalizeWhitespace(unescapeXml(quote)).toLowerCase();

      const isSubstr =
        normalizedChunkText.includes(normalizedQuote) ||
        normalizedChunkText.includes(unescapedNormalizedQuote);

      if (!isSubstr) {
        // Discard unverifiable excerpts rather than inventing a replacement
        droppedCitations.push({
          chunkId,
          quote,
          reason: `Cited quote could not be verified within chunk "${chunkId}" text.`,
        });
        continue;
      }

      // 6. Respect upper bound on citations (cannot exceed retrieved chunk count)
      if (validatedCitations.length >= maxAllowed) {
        droppedCitations.push({
          chunkId,
          quote,
          reason: `Maximum citation limit of ${maxAllowed} reached.`,
        });
        continue;
      }

      // Citation is valid!
      seenChunkIds.add(chunkId);
      validatedCitations.push({
        id: matchingChunk.id,
        title: matchingChunk.sourceTitle,
        section: matchingChunk.sectionTitle,
        excerpt: quote,
      });
    }

    // 7. Groundedness determination:
    // If the model claimed sufficient evidence, but zero valid citations survived, the answer is ungrounded.
    const isUngrounded =
      hasSufficientEvidence &&
      candidateCitations.length > 0 &&
      validatedCitations.length === 0;

    return {
      validatedCitations,
      droppedCitations,
      isUngrounded,
    };
  }
}

